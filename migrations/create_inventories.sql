-- PostgreSQL: jalankan pada database new_analytics yang masih kosong.
-- Membuat tabel induk users terlebih dahulu, lalu inventories dengan FK ke users.id.
create table if not exists users (
  id integer generated by default as identity primary key,
  name varchar(120) not null,
  email varchar(255) not null unique,
  role varchar(30) not null default 'user' check (role in ('admin', 'user')),
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp
);

create table if not exists inventories (
  id integer generated by default as identity primary key,
  name text not null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  user_id integer not null references users (id) on delete restrict,
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp
);

create index if not exists ix_inventories_user_id on inventories (user_id);

